
const express = require('express');
const cors = require('cors');
require('dotenv').config();

// Importar base de datos PostgreSQL
const db = require('./config/database');

// Importar rutas de productos
const productoRoutes = require('./routes/productoRoutes');

const app = express();

// Middlewares
app.use(cors({
    origin: process.env.FRONTEND_URL || 'http://localhost:5173'
}));

app.use(express.json());

// Ruta principal
app.get('/', (req, res) => {
    res.json({
        mensaje: 'API de Gestión de Inventario funcionando correctamente'
    });
});

// Comprobar conexión con PostgreSQL
app.get('/api/estado', async (req, res) => {
    try {
        const resultado = await db.query('SELECT 1 AS conexion');

        res.json({
            mensaje: 'API y base de datos funcionando correctamente',
            conexion: Number(resultado.rows[0].conexion)
        });
    } catch (error) {
        console.error('Error en la conexión:', error.message);

        res.status(500).json({
            mensaje: 'Error al conectar con la base de datos'
        });
    }
});

// Registrar las rutas de productos
app.use('/api/productos', productoRoutes);

// Puerto dinámico
const PORT = process.env.PORT || 3000;

// Crear tabla e iniciar servidor
const iniciarServidor = async () => {
    try {
        await db.query(`
            CREATE TABLE IF NOT EXISTS productos (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre TEXT NOT NULL,
                categoria TEXT NOT NULL,
                precio DOUBLE PRECISION NOT NULL CHECK (precio > 0),
                stock INTEGER NOT NULL CHECK (stock >= 0)
            )
        `);

        console.log('Tabla productos verificada o creada en Supabase.');

        app.listen(PORT, () => {
            console.log(`Servidor ejecutándose en el puerto ${PORT}`);
        });

    } catch (error) {
        console.error('Error al iniciar el servidor:', error.message);
        process.exit(1);
    }
};

iniciarServidor();
